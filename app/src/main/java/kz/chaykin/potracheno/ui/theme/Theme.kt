/** Скругления покрупнее стандартных: интерфейс лёгкий и «пузырчатый». */
private val PotrachenoShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(18.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(32.dp),
)

private val LocalBrandColors = staticCompositionLocalOf { LightBrand }
private val LocalCategoryColors = staticCompositionLocalOf { LightCategoryColors }

/** Цвета со смыслом: `MaterialTheme.brandColors.positive`. */
val MaterialTheme.brandColors: BrandColors
    @Composable
    @ReadOnlyComposable
    get() = LocalBrandColors.current

/** Цвет категории: `MaterialTheme.categoryColors[category]`. */
val MaterialTheme.categoryColors: CategoryColors
    @Composable
    @ReadOnlyComposable
    get() = LocalCategoryColors.current

/**
 * Своя палитра без Material You: яркость — часть характера приложения,
 * и серо-бежевые обои её бы съели.
 */
@Composable
fun PotrachenoTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    CompositionLocalProvider(
        LocalBrandColors provides if (darkTheme) DarkBrand else LightBrand,
        LocalCategoryColors provides if (darkTheme) DarkCategoryColors else LightCategoryColors,
    ) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkScheme else LightScheme,
            typography = PotrachenoTypography,
            shapes = PotrachenoShapes,
            content = content,
        )
    }
}
